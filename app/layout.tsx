// iOS home-screen launch images — without these a PWA cold launch flashes a
// blank screen. Generated by scripts/make-icons.py (public/splash/); one
// entry per (device points × pixel ratio) the group's iPhones use.
const SPLASH_SCREENS = [
  { w: 375, h: 812, r: 3 },
  { w: 390, h: 844, r: 3 },
  { w: 393, h: 852, r: 3 },
  { w: 402, h: 874, r: 3 },
  { w: 414, h: 896, r: 2 },
  { w: 428, h: 926, r: 3 },
  { w: 430, h: 932, r: 3 },
  { w: 440, h: 956, r: 3 },
];

// The footer is the only thing in the layout that needs price data. Loading
// it inside its own Suspense boundary (instead of awaiting in RootLayout)
// lets the shell — and the launch splash — stream to the phone immediately
// rather than waiting on the GitHub data read first.
async function DataFooter() {
  const data = await loadPriceData();
  const lastDate = data.tradingDates[data.tradingDates.length - 1];
  return <Footer lastDate={lastDate} generatedAt={data.generatedAt} />;
}

// Runs before first paint: once this session has seen the splash, hide it
// so reloads don't replay it (see components/Splash.tsx).
const SPLASH_SKIP_SCRIPT = `try{if(sessionStorage.getItem(${JSON.stringify(
  SPLASH_SEEN_KEY
)}))document.documentElement.dataset.splash="skip"}catch(e){}`;

// Theme before first paint. ThemeController only runs after hydration, so
// without this the page painted dark and then cross-faded to the light /
// twilight palette — the launch "flicker". The server renders the theme for
// the current market session (every page is force-dynamic), and this script
// applies any pinned ?theme override from localStorage before paint.
const THEME_SCRIPT = `try{var p=new URLSearchParams(location.search).get("theme"),o=p&&p!=="auto"?p:p==="auto"?null:localStorage.getItem("theme-override"),r=document.documentElement;if(o==="light"||o==="twilight")r.dataset.theme=o;else if(o==="dark")delete r.dataset.theme}catch(e){}`;

function serverTheme(): string | undefined {
  const state = getMarketSessionState();
  if (state === "open") return "light";
  if (state === "premarket" || state === "afterhours") return "twilight";
  return undefined;
}

export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    // suppressHydrationWarning: the inline splash script may set
    // data-splash on <html> before React hydrates.
    <html lang="en" className="h-full" data-theme={serverTheme()} suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: SPLASH_SKIP_SCRIPT + THEME_SCRIPT }} />
        {SPLASH_SCREENS.map(({ w, h, r }) => (
          <link
            key={`${w}x${h}@${r}`}
            rel="apple-touch-startup-image"
            media={`(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: portrait)`}
            href={`/splash/splash-${w * r}x${h * r}.png`}
          />
        ))}
      </head>
      <body className="min-h-full bg-page text-ink antialiased">
        <Splash />
        <ThemeController />
        <ServiceWorkerRegistrar />
        <InstallHint />
        <PullToRefresh />
        <MotionProvider>
          <main
            className="max-w-md mx-auto pb-20"
            style={{ paddingTop: "env(safe-area-inset-top)" }}
          >
            {children}
            <Suspense fallback={null}>
              <DataFooter />
            </Suspense>
          </main>
        </MotionProvider>
        <TabBar />
        {/* Status-bar backdrop. With black-translucent the page draws under
            the clock, so on the tab routes (no sticky HeaderBack) scrolled
            content collided with the status bar. Same frosted chrome as
            HeaderBack, which sits above this (z-30) on detail routes.
            Zero-height wherever there's no top inset. */}
        <div
          aria-hidden
          className="fixed top-0 inset-x-0 z-20 bg-chrome-soft backdrop-blur-md pointer-events-none"
          style={{ height: "env(safe-area-inset-top)" }}
        />
      </body>
    </html>
  );
}
